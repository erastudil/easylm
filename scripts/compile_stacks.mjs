import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stacksDir = join(root, 'stacks');
const packs = JSON.parse(readFileSync(join(stacksDir, 'PACKS.json'), 'utf8'));

function extractUnits(textbook, dewey, slug) {
  const units = [];
  // Skip a leading YAML frontmatter block (--- ... ---): its key: value
  // lines otherwise match the Progen pattern and become junk units
  // (e.g. topic "status", "floor_age", "level") that pollute Stacks search.
  let source = textbook;
  if (source.startsWith('---\n')) {
    const end = source.indexOf('\n---\n', 4);
    if (end !== -1) source = source.slice(end + 5);
  }
  const lines = source.split(/\r?\n/);
  let currentChapter = 'General';

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (line.startsWith('## ')) {
      currentChapter = line.replace(/^##\s+/, '').trim();
      continue;
    }
    // Pattern 1: Bold bullet: - **topic**: comment or * **topic** — comment
    const bulletMatch = line.match(/^[-*]\s+\*\*([^*]+)\*\*[:—\-]\s+(.+)$/);
    if (bulletMatch) {
      units.push({
        topic: bulletMatch[1].trim(),
        comment: bulletMatch[2].trim(),
        dewey,
        chapter: currentChapter,
        slug
      });
      continue;
    }
    // Pattern 2: Progen topic : comment
    const progenMatch = line.match(/^([^:]{2,60}):\s+([A-Za-z0-9].+)$/);
    if (progenMatch && !line.startsWith('http') && !line.startsWith('#') && !line.startsWith('|')) {
      const top = progenMatch[1].trim();
      if (!top.includes('http') && top.split(/\s+/).length <= 6 && !/^\d+$/.test(top)) {
        units.push({
          topic: top,
          comment: progenMatch[2].trim(),
          dewey,
          chapter: currentChapter,
          slug
        });
      }
    }
  }
  return units;
}

// Normalize line endings on read: a textbook saved with CRLF (Windows)
// otherwise embeds \r\n escapes in the compiled output, so regenerating
// on a different OS produces a large content-free diff.
const normalizeEol = (s) => s.replace(/\r\n/g, '\n').replace(/\r/g, '\n');

function extractFrontMatterMeta(textbook) {
  const m = textbook.replace(/^\uFEFF/, '').match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_]+):\s*(.+)$/);
    if (kv) fm[kv[1].toLowerCase()] = kv[2].trim();
  }
  return fm;
}

const compiled = packs.map((p) => {
  const dir = join(stacksDir, p.slug);
  const textbook = normalizeEol(readFileSync(join(dir, 'TEXTBOOK.md'), 'utf8'));
  const links = normalizeEol(readFileSync(join(dir, 'LINK_INDEX.md'), 'utf8'));
  const fm = extractFrontMatterMeta(textbook);
  const level = p.level || fm.level;
  const floorAgeRaw = p.floor_age ?? (fm.floor_age ? Number(fm.floor_age) : undefined);
  const units = extractUnits(textbook, p.dewey, p.slug);
  return {
    ...p,
    ...(level ? { level } : {}),
    ...(floorAgeRaw !== undefined ? { floor_age: floorAgeRaw } : {}),
    textbook,
    links,
    units
  };
});

const outStacks = join(root, 'src', 'data', 'stacks_compiled.ts');
mkdirSync(dirname(outStacks), { recursive: true });

const body =
  '/* generated by scripts/compile_stacks.mjs — do not hand-edit */\n' +
  'export interface StackUnit {\n' +
  '  topic: string;\n' +
  '  comment: string;\n' +
  '  dewey: string;\n' +
  '  chapter: string;\n' +
  '  slug: string;\n' +
  '}\n\n' +
  'export interface StackPack {\n' +
  '  slug: string;\n' +
  '  dewey: string;\n' +
  '  title: string;\n' +
  '  category: string;\n' +
  '  keywords: string[];\n' +
  '  level?: string;\n' +
  '  floor_age?: number;\n' +
  '  textbook: string;\n' +
  '  links: string;\n' +
  '  units?: StackUnit[];\n' +
  '}\n\n' +
  'export const STACKS_PACKS: StackPack[] = ' +
  JSON.stringify(compiled, null, 2) +
  ';\n';

writeFileSync(outStacks, body, 'utf8');
const totalUnits = compiled.reduce((acc, p) => acc + (p.units ? p.units.length : 0), 0);
console.log(`compiled ${compiled.length} academic packs, ${totalUnits} atomic units from stacks -> ${outStacks}`);
